import { randomUUID } from 'node:crypto';
import { mkdir, rename, writeFile } from 'node:fs/promises';
import { generateSpec } from 'har-to-openapi';
import path from 'node:path';

/**
 * Shared file writer used by every recording front-end (WTR plugin, Storybook addon).
 *
 * Output: `<outputDir>/<source>/<file>.<producer>.openapi.json` (plus `.har` when `har` is enabled), one
 * document per `file` **per producer**. All options are already resolved by the caller.
 *
 * @param {{ source: 'wtr' | 'storybook', outputDir: string, rootDir: string, executionId: string, pathSegments: number, openApi: boolean, har: boolean }} options
 */
export function createInteractionWriter({ source, outputDir, executionId, pathSegments, openApi, har }) {
  /** @type {Map<string, { diagnostics: string[], groups: Map<string, { host: string, pathPrefix: string, interactions: object[] }> }>} */
  const files = new Map();
  const writes = new Map();
  const fileField = source === 'wtr' ? '_testFile' : '_storiesFile';

  return {
    /**
     * @param {{ file: string, interactions: object[], diagnostics: string[] }} input `file` is a relative POSIX path
     * @returns {Promise<boolean>}
     */
    async save({ file, interactions, diagnostics }) {
      const fileState = files.get(file) ?? { diagnostics: [], groups: new Map() };
      files.set(file, fileState);
      fileState.diagnostics.push(...diagnostics);

      /** @type {Map<string, object[]>} interactions from this call only, grouped by producer key */
      const batch = new Map();
      for (const interaction of interactions) {
        const producer = describeProducer(interaction.request.url, pathSegments);
        if (!fileState.groups.has(producer.key)) {
          fileState.groups.set(producer.key, { host: producer.host, pathPrefix: producer.pathPrefix, interactions: [] });
        }
        (batch.get(producer.key) ?? batch.set(producer.key, []).get(producer.key)).push(interaction);
      }
      if (!batch.size) return true; // nothing attributable to a producer this round

      const writeGroup = async key => {
        const base = path.join(outputDir, source, `${file}.${key}`);
        const previousWrite = writes.get(base) ?? Promise.resolve();
        const write = previousWrite.catch(() => {}).then(async () => {
          const group = fileState.groups.get(key);
          group.interactions.push(...batch.get(key));

          const document = {
            log: {
              version: '1.2',
              creator: { name: 'web-mocks-recorder', version: '0.1.0' },
              entries: group.interactions.map(toHarEntry),
              _executionId: executionId,
              _source: source,
              [fileField]: file,
              _producer: { host: group.host, pathPrefix: group.pathPrefix },
              ...(fileState.diagnostics.length && { _diagnostics: fileState.diagnostics }),
            },
          };
          await mkdir(path.dirname(base), { recursive: true });

          if (openApi) {
            const specPath = `${base}.openapi.json`;
            try {
              const { spec } = await generateSpec(document, {
                relaxedMethods: true,
                infoTitle: `${group.host}${group.pathPrefix} API`,
                infoVersion: '1.0.0',
                infoDescription: `OpenAPI spec generated by web-mocks-recorder from @web/mocks interactions recorded by "${file}" on {generatedAt}.`,
              });
              const specTmp = `${specPath}.${process.pid}.${randomUUID()}.tmp`;
              await writeFile(specTmp, JSON.stringify(spec, null, 2) + '\n');
              await rename(specTmp, specPath);
            } catch (error) {
              const message = `[web-mocks-recorder] OpenAPI spec not generated for ${path.basename(specPath)}: ${error instanceof Error ? error.message : 'unknown error'}`;
              fileState.diagnostics.push(message);
            }
          }

          if (har) {
            const harPath = `${base}.har`;
            const tmp = `${harPath}.${process.pid}.${randomUUID()}.tmp`;
            await writeFile(tmp, JSON.stringify(document, null, 2) + '\n');
            await rename(tmp, harPath);
          }
          return true;
        });
        writes.set(base, write);
        try {
          return await write;
        } finally {
          if (writes.get(base) === write) writes.delete(base);
        }
      };

      const results = await Promise.all([...batch.keys()].map(writeGroup));
      return results.every(Boolean);
    },
  };
}

/**
 * Derives the "producer" a request belongs to: its hostname (port is ignored so a dev server's randomly
 * assigned port doesn't fragment a single backend into multiple files) plus its first `pathSegments` path
 * segments. Unparsable URLs fall into a single `unknown` bucket rather than being dropped.
 *
 * @param {string} url
 * @param {number} pathSegments
 * @returns {{ key: string, host: string, pathPrefix: string }}
 */
function describeProducer(url, pathSegments) {
  let host = 'unknown-host';
  let segments = [];
  try {
    const parsed = new URL(url);
    host = parsed.hostname || host;
    segments = parsed.pathname.split('/').filter(Boolean).slice(0, pathSegments);
  } catch {
    // leave the defaults; the interaction still gets recorded, just ungrouped by path.
  }
  const pathPrefix = segments.length ? `/${segments.join('/')}` : '';
  const key = sanitizeForFilename([host, ...segments].join('-') || 'unknown');
  return { key, host, pathPrefix };
}

function sanitizeForFilename(value) {
  return value.replace(/[^A-Za-z0-9._-]+/g, '-');
}

function toHarEntry(interaction) {
  const { request, response } = interaction;
  const requestHeaders = toHarHeaders(request.headers);
  const responseHeaders = toHarHeaders(response.headers);
  const requestBodySize = getBodySize(request.body, interaction.diagnostics, 'request.body');
  const responseBodySize = getBodySize(response.body, interaction.diagnostics, 'response.body');
  const url = new URL(request.url);
  const requestContentType = request.headers['content-type']?.[0] ?? '';
  const responseContentType = response.headers['content-type']?.[0] ?? '';

  return {
    startedDateTime: interaction.timestamp,
    time: -1,
    request: {
      method: request.method,
      url: request.url,
      httpVersion: '',
      cookies: parseRequestCookies(request.headers.cookie ?? []),
      headers: requestHeaders,
      queryString: [...url.searchParams].map(([name, value]) => ({ name, value })),
      headersSize: -1,
      bodySize: requestBodySize,
      ...(request.body !== null && {
        postData: { mimeType: requestContentType, text: request.body },
      }),
    },
    response: {
      status: response.status,
      statusText: response.statusText,
      httpVersion: '',
      cookies: parseResponseCookies(response.headers['set-cookie'] ?? []),
      headers: responseHeaders,
      content: {
        size: responseBodySize,
        mimeType: responseContentType,
        ...(response.body !== null && { text: response.body }),
      },
      redirectURL: response.headers.location?.[0] ?? '',
      headersSize: -1,
      bodySize: responseBodySize,
    },
    cache: {},
    timings: { blocked: -1, dns: -1, connect: -1, send: -1, wait: -1, receive: -1, ssl: -1 },
    _executionId: interaction.executionId,
    _source: interaction.source,
    ...(interaction.story && {
      _story: { id: interaction.story.id, title: interaction.story.title, name: interaction.story.name },
    }),
    ...(interaction.diagnostics && { _diagnostics: interaction.diagnostics }),
  };
}

function getBodySize(body, diagnostics, target) {
  if (body === null) return diagnostics?.some(diagnostic => diagnostic.target === target) ? -1 : 0;
  return new TextEncoder().encode(body).byteLength;
}

function toHarHeaders(headers) {
  return Object.entries(headers).flatMap(([name, values]) => values.map(value => ({ name, value })));
}

function parseRequestCookies(values) {
  return values.flatMap(value =>
    value.split(';').map(cookie => cookie.trim()).filter(Boolean).map(cookie => {
      const separator = cookie.indexOf('=');
      return { name: separator < 0 ? cookie : cookie.slice(0, separator), value: separator < 0 ? '' : cookie.slice(separator + 1) };
    }),
  );
}

function parseResponseCookies(values) {
  return values.flatMap(value => {
    const [pair, ...attributes] = value.split(';').map(part => part.trim());
    const separator = pair.indexOf('=');
    if (separator < 0) return [];
    const cookie = { name: pair.slice(0, separator), value: pair.slice(separator + 1) };
    for (const attribute of attributes) {
      const split = attribute.indexOf('=');
      const name = (split < 0 ? attribute : attribute.slice(0, split)).toLowerCase();
      const value = split < 0 ? '' : attribute.slice(split + 1);
      if (name === 'path' || name === 'domain' || name === 'expires') cookie[name] = value;
      else if (name === 'httponly' || name === 'secure') cookie[name] = true;
    }
    return [cookie];
  });
}
